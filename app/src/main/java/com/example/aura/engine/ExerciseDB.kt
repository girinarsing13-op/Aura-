    fun resolveMuscles(exerciseName: String, muscleCategory: String): Pair<String, List<String>> {
        val n = exerciseName.lowercase().trim()
        val cat = muscleCategory.lowercase().trim()
        return when {
            // Chest
            n.contains("incline dumbbell press") || n.contains("incline bench") || n.contains("incline chest") ->
                "Upper Chest" to listOf("Front Delts", "Triceps")
            n.contains("bench press") || n.contains("chest press") || n.contains("floor press") ->
                "Chest" to listOf("Front Delts", "Triceps")
            n.contains("pec deck") || n.contains("chest fly") || n.contains("crossover") ->
                "Chest" to listOf("Front Delts")
            n.contains("push-up") || n.contains("pushup") ->
                "Chest" to listOf("Triceps", "Core")
            n.contains("dips") ->
                "Lower Chest" to listOf("Triceps", "Front Delts")
            cat == "chest" ->
                "Chest" to listOf("Triceps", "Front Delts")

            // Back
            n.contains("front lever") ->
                "Lats" to listOf("Core", "Rear Delts")
            n.contains("muscle-up") ->
                "Lats" to listOf("Chest", "Triceps", "Biceps")
            n.contains("lat pulldown") || n.contains("pulldown") ->
                "Lats" to listOf("Biceps", "Upper Back")
            n.contains("pull-up") || n.contains("chin-up") ->
                "Lats" to listOf("Biceps", "Forearms")
            n.contains("cable row") || n.contains("seated row") ->
                "Mid Back" to listOf("Lats", "Biceps")
            n.contains("t-bar") || n.contains("barbell row") || n.contains("dumbbell row") || n.contains("chest-supported row") ->
                "Back" to listOf("Lats", "Biceps", "Rhomboids")
            n.contains("deadlift") ->
                "Back" to listOf("Glutes", "Hamstrings", "Spinal Erectors")
            n.contains("shrug") ->
                "Traps" to listOf("Upper Back")
            n.contains("pullover") ->
                "Lats" to listOf("Teres Major", "Triceps")
            cat == "back" ->
                "Back" to listOf("Lats", "Biceps")

            // Shoulders
            n.contains("handstand") ->
                "Shoulders" to listOf("Triceps", "Core")
            n.contains("overhead press") || n.contains("shoulder press") || n.contains("military press") || n.contains("arnold press") ->
                "Shoulders" to listOf("Front Delts", "Triceps")
            n.contains("lateral raise") || n.contains("side raise") ->
                "Lateral Delts" to listOf("Traps")
            n.contains("rear delt") || n.contains("face pull") || n.contains("reverse fly") || n.contains("reverse pec deck") || n.contains("pull-apart") ->
                "Rear Delts" to listOf("Rhomboids", "Traps")
            n.contains("front raise") ->
                "Front Delts" to listOf("Upper Chest")
            cat == "shoulders" ->
                "Shoulders" to listOf("Triceps")

            // Biceps
            n.contains("hammer curl") ->
                "Biceps" to listOf("Brachialis", "Forearms")
            n.contains("preacher curl") || n.contains("incline curl") || n.contains("bicep curl") || n.contains("curl") ->
                "Biceps" to listOf("Brachialis", "Forearms")
            cat == "biceps" ->
                "Biceps" to listOf("Forearms")

            // Triceps
            n.contains("pushdown") || n.contains("tricep extension") || n.contains("tricep pushdown") ->
                "Triceps" to listOf("Forearms")
            n.contains("skull crusher") || n.contains("skullcrusher") || n.contains("overhead extension") || n.contains("french press") ->
                "Triceps" to listOf("Forearms")
            n.contains("close-grip") ->
                "Triceps" to listOf("Chest", "Front Delts")
            cat == "triceps" ->
                "Triceps" to listOf("Forearms")

            // Quads / Legs
            n.contains("leg press") ->
                "Quads" to listOf("Glutes")
            n.contains("wall sit") ->
                "Quads" to listOf("Glutes")
            n.contains("squat") || n.contains("hack squat") ->
                "Quads" to listOf("Glutes", "Adductors")
            n.contains("leg extension") ->
                "Quads" to emptyList()
            n.contains("lunge") || n.contains("split squat") || n.contains("step up") ->
                "Quads" to listOf("Glutes", "Hamstrings")

            // Hamstrings
            n.contains("nordic") ->
                "Hamstrings" to listOf("Glutes", "Calves")
            n.contains("leg curl") || n.contains("hamstring curl") ->
                "Hamstrings" to listOf("Calves")
            n.contains("romanian deadlift") || n.contains("rdl") || n.contains("stiff-leg") ->
                "Hamstrings" to listOf("Glutes", "Lower Back")
            n.contains("hip thrust") || n.contains("glute bridge") ->
                "Glutes" to listOf("Hamstrings")
            cat == "hamstrings" ->
                "Hamstrings" to listOf("Glutes")

            // Glutes
            n.contains("kickback") ->
                "Glutes" to listOf("Hamstrings")
            cat == "glutes" ->
                "Glutes" to listOf("Hamstrings")

            // Calves
            n.contains("calf") ->
                "Calves" to listOf("Soleus", "Gastrocnemius")
            cat == "calves" ->
                "Calves" to listOf("Soleus")

            // Abs / Core
            n.contains("l-sit") || n.contains("windshield") || n.contains("bird dog") || n.contains("dead bug") || n.contains("hollow") || n.contains("crunch") || n.contains("plank") || n.contains("leg raise") || n.contains("ab wheel") ->
                "Abs" to listOf("Core", "Obliques")
            cat == "abs" || cat == "core" ->
                "Abs" to listOf("Core")

            cat == "legs" ->
                "Quads" to listOf("Glutes", "Hamstrings")

            else ->
                muscleCategory.replaceFirstChar { it.uppercase() } to emptyList()
        }
    }
